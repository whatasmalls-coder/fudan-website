"""校曆 PDF 解析規則的回歸測試（只用 Python 標準函式庫，CI 每次 push 都會跑）。

PDF 表格裡太長的活動名稱會在格子裡換行，scrape_calendar.merge_wrapped_lines()
負責把被切開的半句黏回去，但兩個獨立的活動不能被誤黏。
下面的例子都來自 115 學年度第 1 學期的真實校曆；改規則前後跑一次，確定沒有退步。

用法：python scripts/test_scrape_calendar.py
"""
import os
import sys
import types

# 這個測試不需要下載 PDF：先放兩個空的模組，讓 scrape_calendar 不用真的安裝 requests / pdfplumber
for name in ("requests", "pdfplumber"):
    sys.modules.setdefault(name, types.ModuleType(name))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scrape_calendar import merge_wrapped_lines  # noqa: E402

# (PDF 一格裡的各行, 期望黏好後的結果)
CASES = [
    # 被格子寬度切開 → 要黏回去
    (["本週國二各班身高體重視", "力量測(健康中心)"], ["本週國二各班身高體重視力量測(健康中心)"]),
    (["本週國三各班身高體重視力", "量測(健康中心)"], ["本週國三各班身高體重視力量測(健康中心)"]),
    (["【晨光】防制學生藥物濫", "用影片宣導"], ["【晨光】防制學生藥物濫用影片宣導"]),
    (["【56】國二友善校園生命", "教育講座"], ["【56】國二友善校園生命教育講座"]),
    (["高三親職講座-大學多元入", "學管道介紹", "【家長場】青年儲蓄戶宣", "導活動", "國三到校自習5"],
     ["高三親職講座-大學多元入學管道介紹", "【家長場】青年儲蓄戶宣導活動", "國三到校自習5"]),
    (["【56】一二年級期中複習", "考(數)"], ["【56】一二年級期中複習考(數)"]),
    # 單獨一行的時間 → 接在上一個活動後面
    (["【56】社團1", "國二九價HPV疫苗接種", "10:30~11:30"], ["【56】社團1", "國二九價HPV疫苗接種 10:30~11:30"]),
    (["流感疫苗接種", "13:00~16:00"], ["流感疫苗接種 13:00~16:00"]),
    # 括號沒關、日期收尾 → 黏回去（原本就有的規則）
    (["學測(1/22~", "1/24)"], ["學測(1/22~1/24)"]),
    # 兩個獨立的活動 → 不能黏
    (["【56】國一班際拔河比賽", "高三模擬考3"], ["【56】國一班際拔河比賽", "高三模擬考3"]),
    (["第二次大考中心英聽測驗", "高二到校自習5"], ["第二次大考中心英聽測驗", "高二到校自習5"]),
    (["【56】國中班際大隊接力比賽", "國3免試入學適性宣導講座(暫定)"],
     ["【56】國中班際大隊接力比賽", "國3免試入學適性宣導講座(暫定)"]),
    (["高一新生健檢週(本週擇一日舉辦)", "生活榮譽競賽開始"], ["高一新生健檢週(本週擇一日舉辦)", "生活榮譽競賽開始"]),
    (["中秋節"], ["中秋節"]),
]


def main() -> int:
    failed = 0
    for lines, expected in CASES:
        got = merge_wrapped_lines(list(lines))
        if got != expected:
            failed += 1
            print(f"✗ {lines}\n    期望 {expected}\n    實際 {got}")
    print(f"校曆換行合併規則：{len(CASES) - failed}/{len(CASES)} 通過")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
